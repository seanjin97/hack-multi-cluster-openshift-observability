"""Snapshots ACM's built-in Grafana dashboards into acm-builtin.md, so you don't need hub access to look them up.
Run after every ACM upgrade, by someone with read access to the hub's observability namespace:
  python3 acm_builtin.py
Needs only oc (logged in to the hub) and the standard library."""
import datetime
import json
import pathlib
import re
import subprocess

NS = "open-cluster-management-observability"
FOLDER = "observability.open-cluster-management.io/dashboard-folder"
OUT = pathlib.Path(__file__).with_name("acm-builtin.md")


def oc(*args):
    return subprocess.check_output(["oc", *args], text=True)


def thanos(path):
    return json.loads(oc("get", "--raw", f"/api/v1/namespaces/{NS}/services/http:observability-thanos-query:9090/proxy/api/v1/{path}"))["data"]


def metrics_in(expr):
    """Metric names in a PromQL expression: identifiers followed by a selector, a range or the end of a term.
    Label matchers, strings and Grafana variables are stripped first."""
    expr = re.sub(r'"[^"]*"|\$\w+|\$\{[^}]*\}', " ", expr)
    expr = re.sub(r"\b(by|without|on|ignoring|group_left|group_right)\s*\([^)]*\)", " ", expr)
    return set(re.findall(r"(?<![\w:])([a-zA-Z_:][\w:]*)\s*(?=\{|\[|\)|,|$|\s*[-+*/]|\s+(?:or|and|unless|offset)\b)", expr)) - {
        "bool", "or", "and", "unless", "offset", "inf", "nan"}


def dashboards(names):
    """One row per title. Prefers the General copy: the 'MCOA' copies need MCOA recording rules."""
    rows = {}
    for cm in json.loads(oc("get", "cm", "-n", NS, "-o", "json"))["items"]:
        meta = cm["metadata"]
        if not meta["name"].startswith("grafana-dashboard-") or "grafana-custom-dashboard" in meta.get("labels", {}):
            continue
        for raw in cm.get("data", {}).values():
            try:
                j = json.loads(raw)
            except ValueError:
                continue
            panels = [p for t in j.get("panels", []) for p in [t, *t.get("panels", [])] if p.get("type") not in ("row", "text")]
            used = set().union(set(), *[metrics_in(t.get("expr", "")) for p in panels for t in p.get("targets", [])])
            have = used & names
            row = dict(
                title=j.get("title", "?"), uid=j.get("uid"), folder=meta.get("annotations", {}).get(FOLDER, "General"),
                filters=[v["name"] for v in j.get("templating", {}).get("list", []) if v.get("type") != "datasource" and v.get("hide", 0) != 2],
                range=j.get("time", {}).get("from", "?").replace("now-", ""),
                panels=sorted({p.get("title", "").strip() for p in panels} - {""}),
                data="yes" if used and have == used else ("partial" if have else "none"),
            )
            prev = rows.get(row["title"])
            if prev is None or prev["folder"].endswith("MCOA") and not row["folder"].endswith("MCOA"):
                if prev:
                    row["also"] = prev["uid"]
                rows[row["title"]] = row
            elif "also" not in prev:
                prev["also"] = row["uid"]
    return sorted(rows.values(), key=lambda r: (r["folder"], r["title"]))


def main():
    version = json.loads(oc("get", "mch", "-A", "-o", "json"))["items"][0]["status"]["currentVersion"]
    names = set(thanos("label/__name__/values"))
    rows = dashboards(names)
    md = [
        "# ACM built-in Grafana dashboards",
        "",
        f"Generated by `acm_builtin.py` on {datetime.date.today()} from ACM {version}. Don't edit; re-run it after an ACM upgrade.",
        "",
        "- **URL:** `/d/<uid>` on ACM's Grafana. Link to one with `dashboard(..., links=[builtin(\"<title>\")])`.",
        "- **Data here:** whether this hub has the metrics the dashboard queries. `none` = the feature isn't installed (e.g. OpenShift Virtualization) or its recording rules aren't forwarded.",
        "- **Copies:** ACM ships most dashboards twice. The `Platform - MCOA` copies need the MCOA addon's recording rules, so the uid below is the General copy where there is one.",
        "- **Never edit these:** the ACM operator overwrites them. Rebuild a panel in your team's dashboard instead (SKILL.md, \"Built-in dashboards\").",
        "",
        "| Dashboard | uid | Folder | Filters | Default range | Data here | Panels |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        uid = f"`{r['uid']}`" + (f"<br/>also `{r['also']}`" if r.get("also") else "")
        md.append(f"| {r['title']} | {uid} | {r['folder']} | {', '.join(r['filters']) or '—'} | {r['range']} | {r['data']} | {'; '.join(r['panels'])} |")
    OUT.write_text("\n".join(md) + "\n")
    print(f"wrote {OUT.name}: {len(rows)} dashboards, ACM {version}")


if __name__ == "__main__":
    main()
