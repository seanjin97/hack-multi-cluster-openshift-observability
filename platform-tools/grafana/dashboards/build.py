"""Builds every dashboard: <team>/<name>.py -> <team>/<name>.json, plus kustomization.yaml.
  uv run build.py            build all
  uv run build.py starforge  build one team's
Each <team>/<name>.py defines `dashboard`. Its uid is <team>-<name> (underscores become dashes), and it
lands in the Grafana folder named after the team."""
import importlib.util
import json
import pathlib
import sys

import standard

HERE = pathlib.Path(__file__).parent


def uid(path):
    """Grafana uid from a dashboard path: starforge/platform_health.py -> starforge-platform-health."""
    return f"{path.parent.name}-{path.stem}".replace("_", "-").lower()


def sources(team=None):
    return sorted(p for p in HERE.glob(f"{team or '*'}/*.py") if not p.name.startswith("_"))


def load(path):
    spec = importlib.util.spec_from_file_location(f"dashboards.{path.parent.name}.{path.stem}", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    assert hasattr(module, "dashboard"), f"{path}: define `dashboard = dashboard(...)`"
    return module.dashboard


def kustomization(paths):
    """kustomization.yaml: one ConfigMap per dashboard, in a folder per team."""
    out = ["# Generated by build.py. Don't edit. GitOps (ArgoCD) syncs this directory to the hub.",
           "namespace: open-cluster-management-observability",
           "resources: [metrics-allowlist.yaml]",
           "generatorOptions:",
           "  disableNameSuffixHash: true   # stable names, so ACM's loader updates rather than duplicates",
           '  labels: {grafana-custom-dashboard: "true"}',
           "configMapGenerator:"]
    for p in paths:
        out += [f"  - name: grafana-dashboard-{uid(p)}",
                f"    files: [{p.parent.name}/{p.stem}.json]",
                f"    options: {{annotations: {{observability.open-cluster-management.io/dashboard-folder: {p.parent.name}}}}}"]
    return "\n".join(out) + "\n"


def main(team=None):
    paths = sources(team)
    assert paths, f"no dashboards in {HERE}/{team or '*'}/"
    for p in paths:
        j = standard.render(load(p), uid(p), p.parent.name)
        p.with_suffix(".json").write_text(json.dumps(j, indent=2, sort_keys=True) + "\n")
        print(f"wrote {p.relative_to(HERE).with_suffix('.json')}: uid {j['uid']}")
    for orphan in set(HERE.glob("*/*.json")) - {p.with_suffix(".json") for p in sources()}:
        orphan.unlink()
        print(f"removed {orphan.relative_to(HERE)}: its .py is gone")
    (HERE / "kustomization.yaml").write_text(kustomization(sources()))


if __name__ == "__main__":
    main(*sys.argv[1:2])
